"""Low-latency shared ALSA capture for the ALSA encoders.

ffmpeg's alsa indev asks for the largest buffer (ALSA_BUFFER_SIZE_MAX); on HDA cards that
forces 4096-frame periods, i.e. audio arrives in 85 ms packets. Encoders instead open
"mr_lowlat:CARD=<id>,DEV=<n>,CH=<hw channels>,RATE=<rate>", defined in a project-local
config handed to ffmpeg via ALSA_CONFIG_PATH (no system / user ALSA config is touched):
plug -> dsnoop -> hw with small periods. dsnoop also lets several encoders capture the
same device; its shared-memory key is derived from card index and device number.
"""
import os

PCM = "mr_lowlat"
SYSTEM_CONF = "/usr/share/alsa/alsa.conf"

_TEMPLATE = """# generated by mediarouter (app/alsa_lowlat.py) - edit config.json "alsa" instead
pcm.{pcm} {{
  @args [ CARD DEV CH RATE ]
  @args.CARD {{ type string }}
  @args.DEV {{ type integer default 0 }}
  @args.CH {{ type integer default 2 }}
  @args.RATE {{ type integer default 48000 }}
  type plug
  slave.pcm {{
    type dsnoop
    ipc_key {{ @func iadd integers [ 4242000 {{ @func imul integers [ {{ @func card_inum card $CARD }} 100 ] }} $DEV ] }}
    ipc_perm 0660
    slave {{
      pcm {{ type hw card $CARD device $DEV }}
      channels $CH
      rate $RATE
      period_size {period}
      buffer_size {buffer}
    }}
  }}
}}
"""


def device(card, pcm, hw_channels, rate):
    return f"{PCM}:CARD={card},DEV={int(pcm)},CH={int(hw_channels)},RATE={int(rate)}"


def env(base_dir, cfg):
    """Environment for an ffmpeg that opens mr_lowlat: (re)writes the config when it changed."""
    period = max(16, int(cfg.get("period_frames") or 240))
    buffer = max(2 * period, int(cfg.get("buffer_frames") or 1920))
    text = _TEMPLATE.format(pcm=PCM, period=period, buffer=buffer)
    path = os.path.join(base_dir, "alsa", "lowlat.conf")
    try:
        with open(path, encoding="utf-8") as f:
            same = f.read() == text
    except OSError:
        same = False
    if not same:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, path)
    return {"ALSA_CONFIG_PATH": f"{SYSTEM_CONF}:{path}"}
